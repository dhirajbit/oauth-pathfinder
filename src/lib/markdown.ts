import type { Guide } from "./schema";

const WHO_LABEL = { agent: "Agent", assisted: "Agent + you", human: "You" } as const;

/** Plain-markdown export so a guide can be pasted into a ticket, README or PR. */
export function guideToMarkdown(g: Guide): string {
  const lines: string[] = [];
  const v = g.verdict;
  lines.push(`# ${g.name} — OAuth app setup guide`);
  lines.push("");
  lines.push(g.summary);
  lines.push("");
  lines.push(`**Difficulty:** ${v.difficulty} — ${v.difficultyReason}`);
  lines.push(`**Hands-on time:** ${v.handsOnMinutes.min}–${v.handsOnMinutes.max} min`);
  lines.push(
    `**Approval wait:** ${v.approvalWait.required === "none" ? "none" : `${v.approvalWait.minDays}–${v.approvalWait.maxDays} days (${v.approvalWait.required})`} — ${v.approvalWait.note}`
  );
  lines.push(`**Time to first token:** ${v.timeToFirstToken}`);
  lines.push(
    `**Composio managed OAuth:** ${g.composio.managedAuthAvailable === null ? "unknown" : g.composio.managedAuthAvailable ? "yes" : "no"}${g.composio.note ? ` — ${g.composio.note}` : ""}`
  );
  lines.push("");
  lines.push("## Prerequisites");
  for (const p of g.prerequisites) lines.push(`- ${p.blocking ? "**[blocking]** " : ""}${p.text}`);
  lines.push("");
  lines.push("## Steps");
  g.steps.forEach((s, i) => {
    lines.push(`${i + 1}. **${s.title}** _(${WHO_LABEL[s.who]})_ — ${s.detail}${s.portalUrl ? ` [Portal](${s.portalUrl})` : ""}`);
    for (const t of s.tips ?? []) lines.push(`   - ${t}`);
  });
  lines.push("");
  lines.push("## Scopes");
  lines.push(g.scopes.note);
  for (const s of g.scopes.examples) lines.push(`- \`${s.scope}\` — ${s.purpose}${s.triggersReview ? " **(triggers review)**" : ""}`);
  lines.push("");
  lines.push("## Approval");
  lines.push(`Required: ${g.approval.required}. ${g.approval.process}`);
  lines.push(`Review time: ${g.approval.reviewTime}`);
  if (g.approval.triggers.length) lines.push(`Triggers: ${g.approval.triggers.join("; ")}`);
  if (g.approval.reviewerAsksFor.length) lines.push(`Reviewers ask for: ${g.approval.reviewerAsksFor.join("; ")}`);
  if (g.approval.commonRejections.length) lines.push(`Common rejections: ${g.approval.commonRejections.join("; ")}`);
  lines.push("");
  lines.push("## Nuances");
  for (const n of g.nuances) lines.push(`- **${n.title}** — ${n.detail}`);
  lines.push("");
  lines.push("## Blockers & workarounds");
  for (const b of g.blockers) lines.push(`- **${b.blocker}** → ${b.workaround}`);
  lines.push("");
  lines.push("## Agent plan");
  lines.push("Agent does:");
  for (const a of g.agentPlan.agentDoes) lines.push(`- ${a}`);
  lines.push("You take over for:");
  for (const h of g.agentPlan.humanDoes) lines.push(`- ${h}`);
  lines.push("");
  lines.push("## Evidence");
  for (const s of g.evidence.sources) lines.push(`- [${s.title}](${s.url}) — ${s.confidence}`);
  if (g.evidence.tested.length) { lines.push(""); lines.push("Tested:"); for (const t of g.evidence.tested) lines.push(`- ${t}`); }
  if (g.evidence.unverified.length) { lines.push(""); lines.push("Unverified:"); for (const u of g.evidence.unverified) lines.push(`- ${u}`); }
  lines.push("");
  lines.push(`_Generated by ${g.meta.generatedBy} on ${g.meta.generatedAt.slice(0, 10)}${g.meta.reviewedBy ? `, reviewed by ${g.meta.reviewedBy}` : ""}._`);
  return lines.join("\n");
}
